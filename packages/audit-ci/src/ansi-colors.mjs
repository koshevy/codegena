const bold = '\u{1B}[1m';
const cyan = '\u{1B}[36m';
const red = '\u{1B}[31m';
const reset = '\u{1B}[0m';
const yellow = '\u{1B}[33m';

const b = bold;
const c = cyan;
const r = red;
const y = yellow;

const cb = `${bold}${cyan}`;
const rb = `${bold}${r}`;
const yb = `${bold}${y}`;

export {
  bold, b,
  cyan, c,
  red, r,
  reset,
  yellow, y,
  cb, rb, yb,
};
